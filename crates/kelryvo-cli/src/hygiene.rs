//! Repository hygiene shared by source tools and chart validation.
use std::{
    ffi::OsStr,
    io::Write,
    path::Path,
    process::{Command, Stdio},
};
type Result<T> = std::result::Result<T, String>;
const OUTPUTS: &[&str] = &[
    ".cache",
    "node_modules",
    "coverage",
    "dist",
    "target",
    "evidence",
    "reports",
    "screenshots",
    "test-results",
    "playwright-report",
    "blob-report",
    "__pycache__",
    ".deps",
    "vendor",
    "vendored",
    "third_party",
    "third-party",
];
const IGNORE_PROBES: &[&str] = &[
    ".cache/reports/result.json",
    "coverage/lcov.info",
    "reports/result.json",
    "screenshots/browser.png",
    "test-results/result.xml",
    "playwright-report/index.html",
    "blob-report/result.zip",
    "evidence/run/result.json",
    "checks.log",
];

pub(crate) fn git(root: &Path, args: &[&str], input: Option<&[u8]>) -> Result<Vec<u8>> {
    let mut child = Command::new("/usr/bin/git")
        .arg("-C")
        .arg(root)
        .args(args)
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .stdin(if input.is_some() {
            Stdio::piped()
        } else {
            Stdio::null()
        })
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| e.to_string())?;
    if let Some(input) = input {
        child
            .stdin
            .take()
            .ok_or("Missing Git input")?
            .write_all(input)
            .map_err(|e| e.to_string())?;
    }
    let output = child.wait_with_output().map_err(|e| e.to_string())?;
    if !output.status.success()
        && !(args.first() == Some(&"check-ignore") && output.status.code() == Some(1))
    {
        return Err("Repository hygiene requires a readable Git checkout".into());
    }
    Ok(output.stdout)
}

pub(crate) fn check(root: &Path) -> Result<()> {
    let application = root.join("Cargo.toml").is_file() && root.join("CHECKLIST.md").is_file();
    let mut manifests = vec![
        "Cargo.toml".to_owned(),
        "tools/oracle-codegen/Cargo.toml".to_owned(),
    ];
    if application {
        let manifest: toml::Table = std::fs::read_to_string(root.join("Cargo.toml"))
            .map_err(|e| e.to_string())?
            .parse()
            .map_err(|e: toml::de::Error| e.to_string())?;
        for member in manifest["workspace"]["members"]
            .as_array()
            .ok_or("Workspace members")?
        {
            manifests.push(format!(
                "{}/Cargo.toml",
                member.as_str().ok_or("Workspace member")?
            ));
        }
    }
    let output = git(
        root,
        &[
            "ls-files",
            "--cached",
            "--others",
            "--exclude-standard",
            "-z",
        ],
        None,
    )?;
    let mut errors = Vec::new();
    for bytes in output.split(|b| *b == 0).filter(|p| !p.is_empty()) {
        let name = std::str::from_utf8(bytes).map_err(|e| e.to_string())?;
        if !root.join(name).exists() {
            continue;
        }
        let parts: Vec<_> = name.split('/').collect();
        let path = Path::new(name);
        let base = parts.last().unwrap();
        let extension = path.extension().and_then(OsStr::to_str).unwrap_or("");
        if parts[..parts.len() - 1].iter().any(|p| OUTPUTS.contains(p))
            || [".coverage", "coverage.xml", "junit.xml", "lcov.info"].contains(base)
            || ["log", "lcov", "pyc"].contains(&extension)
        {
            errors.push(format!("Generated output must stay outside Git: {name:?}"));
        }
        if application && prohibited_source(name, &manifests) {
            errors.push(format!(
                "Unreviewed dependency/generated source in Git: {name:?}"
            ));
        }
        if application && extension == "rs" {
            let source = std::fs::read_to_string(root.join(name)).map_err(|e| e.to_string())?;
            if source.lines().take(32).any(|line| {
                [
                    "// Generated by",
                    "// Code generated",
                    "// @generated",
                    "// Copyright",
                    "/* Copyright",
                    "// SPDX-License-Identifier:",
                    "// Licensed under",
                ]
                .iter()
                .any(|marker| line.trim_start().starts_with(marker))
            }) {
                errors.push(format!(
                    "Review source ownership before tracking upstream/generated Rust: {name:?}"
                ));
            }
        }
    }

    let checklist = root.join("CHECKLIST.md").is_file();
    let chart = root.join("Chart.yaml").is_file();
    if checklist && chart {
        errors.push("Helm must link to the app checklist instead of duplicating it".into());
    }
    if !checklist && !chart {
        errors.push("Application checkout must contain CHECKLIST.md".into());
    }
    let input = IGNORE_PROBES.join("\0") + "\0";
    let ignored = git(
        root,
        &["check-ignore", "--no-index", "--stdin", "-z"],
        Some(input.as_bytes()),
    )?;
    for probe in IGNORE_PROBES {
        if !ignored.split(|b| *b == 0).any(|p| p == probe.as_bytes()) {
            errors.push(format!("Missing generated-output ignore rule: {probe}"));
        }
    }
    if application {
        for probe in [
            ".deps/antlr-rust-runtime/src/lib.rs",
            "target/debug/app",
            "crates/kelryvo-oracle-grammar/src/generated/pl_sql_parser.rs",
            "crates/kelryvo-oracle-grammar/grammar/PlSqlLexer.g4",
            "crates/kelryvo-oracle-grammar/grammar/PlSqlParser.g4",
            "crates/kelryvo-oracle-grammar/grammar/provenance.json",
        ] {
            if git(root, &["check-ignore", "--no-index", probe], None)?.is_empty() {
                errors.push(format!(
                    "Missing dependency/generated source ignore: {probe}"
                ));
            }
        }
        for retained in [
            "Cargo.lock",
            "tools/oracle-codegen/Cargo.lock",
            "LICENSE",
            "crates/kelryvo-oracle-grammar/upstream/PlSqlParser.g4",
            "tests/fixtures/contracts/core.json.gz",
        ] {
            if !git(root, &["check-ignore", "--no-index", retained], None)?.is_empty() {
                errors.push(format!("Required immutable input is ignored: {retained}"));
            }
        }
    }
    if !errors.is_empty() {
        return Err(errors.join("\n"));
    }
    println!("PASS: generated outputs ignored and absent from Git");
    Ok(())
}

fn prohibited_source(name: &str, manifests: &[String]) -> bool {
    let grammar = [
        "crates/kelryvo-oracle-grammar/upstream/PlSqlLexer.g4",
        "crates/kelryvo-oracle-grammar/upstream/PlSqlParser.g4",
    ];
    let parts: Vec<_> = name.split('/').collect();
    let extension = Path::new(name)
        .extension()
        .and_then(OsStr::to_str)
        .unwrap_or("");
    (extension == "rs"
        && !name.starts_with("tests/")
        && ![
            "tools/dependency_source.rs",
            "tools/oracle-codegen/src/main.rs",
        ]
        .contains(&name)
        && !manifests
            .iter()
            .filter_map(|p| p.strip_suffix("/Cargo.toml"))
            .any(|directory| name.starts_with(&format!("{directory}/"))))
        || (name.ends_with("Cargo.toml") && !manifests.iter().any(|p| p == name))
        || (parts.contains(&"upstream") && !grammar.contains(&name))
        || name.starts_with("crates/kelryvo-oracle-grammar/src/generated/")
        || [
            "crates/kelryvo-oracle-grammar/grammar/PlSqlLexer.g4",
            "crates/kelryvo-oracle-grammar/grammar/PlSqlParser.g4",
            "crates/kelryvo-oracle-grammar/grammar/provenance.json",
        ]
        .contains(&name)
        || [
            "crate", "o", "a", "rlib", "rmeta", "so", "wasm", "exe", "dll", "dylib",
        ]
        .contains(&extension)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn force_added_cache_and_disguised_dependency_fail_the_repository_gate() {
        let directory = tempfile::tempdir().unwrap();
        let root = directory.path();
        git(root, &["init", "--quiet"], None).unwrap();
        std::fs::write(root.join("CHECKLIST.md"), "Retained checklist\n").unwrap();
        std::fs::write(root.join("Cargo.toml"), "[workspace]\nmembers=[]\n").unwrap();
        std::fs::copy(
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.gitignore"),
            root.join(".gitignore"),
        )
        .unwrap();
        check(root).unwrap();
        std::fs::create_dir_all(root.join(".deps/cache")).unwrap();
        std::fs::write(root.join(".deps/cache/input.rs"), "cached dependency\n").unwrap();
        git(root, &["add", "--force", ".deps/cache/input.rs"], None).unwrap();
        assert!(
            check(root)
                .unwrap_err()
                .contains("Generated output must stay outside Git")
        );
        git(root, &["rm", "--cached", ".deps/cache/input.rs"], None).unwrap();
        std::fs::create_dir_all(root.join("crates/ordinary-name")).unwrap();
        std::fs::write(
            root.join("crates/ordinary-name/Cargo.toml"),
            "[package]\nname='copied'\n",
        )
        .unwrap();
        assert!(
            check(root)
                .unwrap_err()
                .contains("Unreviewed dependency/generated source")
        );
    }
    #[test]
    fn dependency_snapshots_and_generated_outputs_need_explicit_review() {
        let manifests = vec!["Cargo.toml".into(), "crates/kelryvo-core/Cargo.toml".into()];
        for name in [
            "crates/renamed-library/Cargo.toml",
            "cache/parser.crate",
            "crates/kelryvo-core/module/upstream/lib.rs",
            "build/app.wasm",
            "crates/kelryvo-oracle-grammar/src/generated/parser.rs",
            "crates/kelryvo-oracle-grammar/grammar/provenance.json",
        ] {
            assert!(prohibited_source(name, &manifests), "{name}");
        }
        for name in [
            "crates/kelryvo-core/Cargo.toml",
            "crates/kelryvo-core/src/backup/profiles.rs",
            "tests/fixtures/contracts/core.json.gz",
            "tests/fixtures/parser/F18/invalid.bin",
            "crates/kelryvo-oracle-grammar/upstream/PlSqlParser.g4",
        ] {
            assert!(!prohibited_source(name, &manifests), "{name}");
        }
    }
}
