import { openTokenRecovery } from './helpers/ui-disclosures.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {createValidationFixture} from './helpers/schema-validation-fixture.mjs';
import {createTlsFixture} from './helpers/product-tls-fixture.mjs';

test('Phase 8 journey authors ordered multi-file SQL and retains plan-bound comparison, approval and request evidence after restart', {
  skip:!process.env.SCHEMAFORGE_TEST_DATABASE_URL,timeout:240000,
},async()=>{
  const cert=await createTlsFixture();let f,browser,page;
  const errors=[],output='.cache/phase8-acceptance';
  try {
    f=await createValidationFixture({tls:cert.tls});await mkdir(output,{recursive:true});
    const launch=async()=>{
      browser=await chromium.launch({args:[`--ignore-certificate-errors-spki-list=${cert.spki}`]});
      page=await browser.newPage({viewport:{width:1440,height:1100}});
      page.setDefaultTimeout(30000);page.on('pageerror',error=>errors.push(error.message));
    };
    const signIn=async(actor,hash='')=>{
      await page.goto(`https://127.0.0.1:${f.app.server.address().port}/${hash}`);
      await openTokenRecovery(page); await page.getByLabel('Local access token').fill(actor.token);
      await page.getByRole('button',{name:'Continue',exact:true}).click();
      await page.getByLabel('Sign out').waitFor();
    };
    const selectProject=async()=>{
      await page.getByRole('button',{name:/Projects/}).first().click();
      await page.locator('.project-row').filter({hasText:f.project.name}).click();
    };
    const logout=async()=>{await page.getByLabel('Sign out').click();await openTokenRecovery(page); await page.getByLabel('Local access token').waitFor();};
    await launch();await signIn(f.actors[0]);await selectProject();
    await page.getByRole('button',{name:/Project targets/}).click();
    await page.getByRole('button',{name:'Inspect binding',exact:true}).click();
    await page.getByRole('button',{name:'Open SQL Workspace for this target',exact:true}).click();
    const workspace=page.getByRole('region',{name:'SQL workspace',exact:true});
    await workspace.getByLabel('SQL workspace target').selectOption(f.binding.bindingId);
    await workspace.getByRole('button',{name:'New draft',exact:true}).click();
    await workspace.getByRole('button',{name:'Save draft',exact:true}).waitFor();
    await workspace.getByLabel('SQL draft name').fill('Phase 8 reviewed SQL');
    const source='CREATE TABLE phase8_authored (id NUMBER);\n';
    await workspace.getByLabel('SQL editor').fill(source);
    await workspace.getByRole('button',{name:'Add SQL file',exact:true}).click();
    await workspace.getByLabel('Migration filename').fill('V2__indexes.sql');
    const secondSource='CREATE INDEX phase8_authored_id ON phase8_authored (id);\n-- café: exact byte context\nALTER TABLE phase8_authored ADD (name VARCHAR2(100));\n';
    await workspace.getByLabel('SQL editor').fill(secondSource);
    await workspace.getByRole('button',{name:'Remove SQL file',exact:true}).click();
    await workspace.getByRole('button',{name:'Undo file removal',exact:true}).click();
    assert.equal(await workspace.getByLabel('SQL editor').inputValue(),secondSource,'removing a file can restore its unsaved content and active identity');

    await workspace.getByRole('button',{name:'Save draft',exact:true}).click();
    await workspace.getByText('Saved revision 2.',{exact:true}).waitFor();
    assert.equal(await workspace.getByLabel('Migration filename').inputValue(),'V2__indexes.sql','save preserves the active file by identity');
    assert.equal(await workspace.getByLabel('SQL editor').inputValue(),secondSource);
    const draftId=new URLSearchParams(new URL(page.url()).hash.slice(1)).get('draft');assert.ok(draftId);
    await workspace.getByLabel('SQL file',{exact:true}).selectOption('0');
    await workspace.getByLabel('SQL editor').fill(source+'-- Unsaved review context\n');
    assert.equal(await workspace.getByRole('button',{name:'Refresh drafts',exact:true}).isDisabled(),true);
    assert.equal(await workspace.getByRole('button',{name:'New draft',exact:true}).isDisabled(),true);
    await page.getByRole('button',{name:/Projects/}).first().click();
    await page.locator('.project-row').filter({hasText:f.project.name}).click();
    await page.getByRole('status').filter({hasText:'Save or discard unsaved SQL edits before selecting a project.'}).waitFor();
    await page.getByRole('button',{name:/Project targets/}).click();
    await page.getByRole('button',{name:/SQL Workspace/}).first().click();
    assert.equal(await workspace.getByLabel('SQL editor').inputValue(),source+'-- Unsaved review context\n','draft edits survive navigation');
    await workspace.getByRole('button',{name:'Discard unsaved edits',exact:true}).click();
    assert.equal(await workspace.getByLabel('SQL editor').inputValue(),source);
    await workspace.getByLabel('SQL editor').fill(source+'-- Failed save context\n');
    const draftPath=`/api/projects/${f.project.id}/sql-drafts/${draftId}`;
    const failedSave=async route=>{
      if(route.request().method()==='PUT')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'INTERNAL_ERROR'})});
      else await route.continue();
    };
    await page.route(`**${draftPath}`,failedSave);
    await workspace.getByRole('button',{name:'Save draft',exact:true}).click();
    await workspace.getByRole('alert').waitFor();
    assert.equal(await workspace.getByLabel('SQL editor').inputValue(),source+'-- Failed save context\n','failed save retains edits for recovery');
    await page.unroute(`**${draftPath}`,failedSave);
    await workspace.getByRole('button',{name:'Discard unsaved edits',exact:true}).click();
    await page.reload();
    await page.waitForFunction(expected=>document.querySelector('textarea[aria-label="SQL editor"]')?.value===expected,source);
    assert.equal(await workspace.getByLabel('SQL editor').inputValue(),source);
    assert.equal(await workspace.getByLabel('SQL workspace target').inputValue(),f.binding.bindingId);
    const reviewing=page.waitForResponse(r=>r.url().endsWith('/preview') && r.request().method()==='POST',{timeout:30000});
    await workspace.getByRole('button',{name:'Review syntax',exact:true}).click();
    const reviewed=await reviewing;assert.equal(reviewed.status(),200,await reviewed.text());
    assert.ok((await reviewed.json()).preview.statements.some(s=>s.classification==='CREATE_TABLE'));
    await workspace.getByText('CREATE_TABLE',{exact:true}).waitFor();
    await workspace.getByRole('button',{name:'Validate against target',exact:true}).click();
    await workspace.getByRole('region',{name:'SQL target validation'}).getByText(/UNVERIFIED/).waitFor();
    await page.screenshot({path:`${output}/01-saved-validated-workspace.png`,fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'SQL workspace remains usable on a narrow viewport');
    await page.setViewportSize({width:1440,height:1100});
    // Statement findings navigate to the correct file and exact UTF-8 source range.
    const validationFindings=workspace.getByRole('region',{name:'SQL target validation'});
    const sourceLink=validationFindings.getByRole('button',{name:/Open SQL source.*V2__indexes.sql/}).last();
    await sourceLink.click();
    assert.equal(await workspace.getByLabel('Migration filename').inputValue(),'V2__indexes.sql');
    await page.waitForFunction(()=>{
      const editor=document.querySelector('.sql-workspace textarea[aria-label="SQL editor"]');
      return editor && /ALTER TABLE phase8_authored/.test(editor.value.slice(editor.selectionStart,editor.selectionEnd));
    });
    const selectedSql=await workspace.getByLabel('SQL editor').evaluate(el=>el.value.slice(el.selectionStart,el.selectionEnd));
    assert.match(selectedSql,/ALTER TABLE phase8_authored/,'finding selects exact statement bytes after a UTF-8 comment');
    const validationPattern=`**/api/projects/${f.project.id}/releases/*/validations`;
    await page.route(validationPattern,async route=>{
      if(route.request().method()==='POST')await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'VALIDATION_PARSER_UNAVAILABLE'})});
      else await route.continue();
    },{times:1});
    await workspace.getByRole('button',{name:'Prepare immutable release',exact:true}).click();
    let planning=workspace.getByRole('button',{name:'Create immutable plan',exact:true});
    await planning.waitFor();
    await workspace.getByRole('alert').filter({hasText:'VALIDATION_PARSER_UNAVAILABLE'}).waitFor();
    assert.equal(await planning.isDisabled(),true,'failed release validation cannot reuse earlier draft validation eligibility');
    await page.unroute(validationPattern);
    const preparedReleaseId=new URLSearchParams(new URL(page.url()).hash.slice(1)).get('release');assert.ok(preparedReleaseId);
    await page.reload();
    await workspace.getByText('Draft and release details',{exact:true}).click();
    await workspace.getByText(preparedReleaseId,{exact:true}).waitFor();
    planning=workspace.getByRole('button',{name:'Create immutable plan',exact:true});
    assert.equal(await planning.isDisabled(),true,'reload restores release identity but requires fresh validation eligibility');
    await workspace.getByRole('button',{name:'Validate against target',exact:true}).click();
    await page.waitForFunction(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent==='Create immutable plan');return b && !b.disabled;});
    await planning.click();
    const planId=await page.locator('.plan-option.selected').getAttribute('data-plan-id');assert.ok(planId);
    const plan=(await f.api('GET',f.base)).json().plans.find(p=>p.id===planId);
    assert.equal(plan.offlineIntent.format,4);
    const release=(await f.api('GET',`/api/releases/${plan.releaseId}`)).json().release;
    assert.equal(release.sourceKind,'AUTHORED_SQL_WORKSPACE');assert.equal(release.draftId,draftId);
    assert.equal(release.files[0].content,source);
    assert.equal(release.files[1].content,secondSource);
    assert.deepEqual(release.files.map(file=>file.version),['1','2']);
    assert.ok(release.files.every(file=>file.draftFileId));
    const record=await f.api('GET',`${f.base}/plans/${planId}/record`);assert.equal(record.statusCode,200,record.body);
    const exported=JSON.parse(record.json().record);assert.equal(exported.retainedIntent.sourceOrigin.sourceKind,'AUTHORED_SQL_WORKSPACE');
    assert.equal(exported.retainedIntent.sourceOrigin.draftId,draftId);
    assert.equal((await f.api('GET',`${f.foreignBase}/sql-drafts/${draftId}`)).statusCode,404);
    await logout();await signIn(f.actors[1]);await selectProject();
    await page.getByRole('button',{name:/Plans & review/}).click();
    await page.locator(`.plan-option[data-plan-id="${planId}"]`).click();
    const retainedValidation=page.getByRole('region',{name:'Retained SQL validation',exact:true});
    await retainedValidation.getByRole('button',{name:/Open SQL source.*V2__indexes.sql/}).last().click();
    const selectedStatement=page.locator('.plan-source-panel .statement-preview-item[data-source-selected="true"]');
    await selectedStatement.waitFor();
    assert.match(await selectedStatement.locator('pre').innerText(),/ALTER TABLE phase8_authored/,'review finding reopens the exact immutable source statement');
    const comparisonPanel=page.getByRole('region',{name:'Plan source comparison'});
    await comparisonPanel.getByLabel('Review baseline').selectOption(f.release.id);
    const comparing=page.waitForResponse(r=>r.url().endsWith(`/plans/${planId}/comparisons`) && r.request().method()==='POST',{timeout:30000});
    await comparisonPanel.getByRole('button',{name:'Compare immutable candidate',exact:true}).click();
    const compared=await comparing;assert.equal(compared.status(),201,await compared.text());
    const comparison=(await compared.json()).comparison;
    await comparisonPanel.getByText('Statement 1 · ADDED',{exact:true}).waitFor();
    const addedStatement=comparisonPanel.locator('details').filter({has:page.locator('summary', {hasText:'Statement 1 · ADDED'})}).last();
    await addedStatement.locator('summary').click();
    await addedStatement.getByRole('button',{name:'Attach candidate statement to comment',exact:true}).click();
    await page.getByLabel('Comment',{exact:true}).fill('Review multi-file changes against the selected immutable baseline');
    const commenting=page.waitForResponse(r=>r.url().endsWith(`/plans/${planId}/comments`) && r.request().method()==='POST');
    await page.getByRole('button',{name:'Add comment',exact:true}).click();
    const commented=await commenting;assert.equal(commented.status(),201,await commented.text());
    await page.getByText('Review multi-file changes against the selected immutable baseline',{exact:true}).waitFor();
    const savedComment=(await commented.json()).comment;
    assert.equal(savedComment.evidenceRefs.length,1);
    assert.equal(savedComment.evidenceRefs[0].releaseId,release.id);
    assert.equal(savedComment.evidenceRefs[0].intentDigest,plan.offlineIntent.digest);
    assert.equal(savedComment.comparisonId,comparison.id);
    const reopening=page.waitForResponse(r=>r.url().endsWith(`/comparisons/${comparison.id}`));
    await page.getByRole('button',{name:'Reopen source comparison',exact:true}).click();
    assert.equal((await reopening).status(),200);
    await page.getByLabel('Decision reason').fill('Independent review of saved authored SQL and exact target evidence');
    await page.getByRole('button',{name:'Approve plan',exact:true}).click();
    await page.getByRole('region',{name:'Decision record'}).waitFor();
    await page.getByRole('region',{name:'Database change review stage'}).getByRole('button',{name:'Open plan history',exact:true}).click();
    const reviewHistory=page.getByRole('region',{name:'Consolidated migration history'});
    assert.equal(await reviewHistory.getByLabel('Search migration history').inputValue(),planId);
    await reviewHistory.getByText('Approval decision',{exact:true}).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('historyPlan'),planId,'plan-specific history has a durable identity link');
    await reviewHistory.getByRole('button',{name:'Open plan',exact:true}).first().click();
    await page.locator(`.plan-option[data-plan-id="${planId}"].selected`).waitFor();
    await page.getByLabel('Plan status',{exact:true}).selectOption('PENDING_APPROVAL');
    await page.getByRole('button',{name:/Migration history/}).click();
    await reviewHistory.getByRole('button',{name:'Open plan',exact:true}).first().click();
    await page.locator(`.plan-option[data-plan-id="${planId}"].selected`).waitFor();
    assert.equal(await page.getByLabel('Plan status',{exact:true}).inputValue(),'ALL','opening an evidence plan clears an incompatible status filter');

    const approval=(await f.db.sql`SELECT facts FROM sf_audit WHERE resource_id=${planId} AND action='PLAN_APPROVED'`)[0].facts;
    assert.equal(approval.comparisonId,comparison.id);
    await logout();await signIn(f.actors[0]);await selectProject();
    await f.membership.deployGrant(f.project.id,f.actors[0].id);
    await page.getByRole('button',{name:'Refresh workspace',exact:true}).click();
    await page.getByRole('button',{name:/Plans & review/}).click();
    await page.locator(`.plan-option[data-plan-id="${planId}"]`).click();
    await page.getByLabel('Request reason').fill('Queue reviewed Phase 8 intent; no Oracle execution authority');
    const requesting=page.waitForResponse(r=>r.url().endsWith(`/plans/${planId}/execution`) && r.request().method()==='POST',{timeout:30000});
    await page.getByRole('button',{name:'Request deployment',exact:true}).click();
    const response=await requesting;assert.equal(response.status(),201,await response.text());
    const {job}=await response.json();assert.equal(job.state,'WAITING_VALIDATION');
    await page.locator('.execution-job').filter({hasText:job.id}).waitFor();
    await page.getByRole('button',{name:/Migration history/}).click();
    let history=page.getByRole('region',{name:'Consolidated migration history'});
    await history.getByLabel('Filter history by target').selectOption(f.binding.bindingId);
    const filtering=page.waitForResponse(r=>{const url=new URL(r.url());return url.pathname.endsWith('/migration-history') && url.searchParams.get('targetId')===f.binding.bindingId && url.searchParams.get('status')==='WAITING_VALIDATION';});
    await history.getByLabel('Filter history by status').selectOption('WAITING_VALIDATION');
    const filtered=await filtering;assert.equal(filtered.status(),200);
    assert.ok((await filtered.json()).items.some(row=>row.jobId===job.id),'exact target history contains the retained request');
    await history.getByText(/Current status · state: WAITING VALIDATION/).waitFor();
    assert.ok((await history.locator('.migration-history-row').filter({hasText:'Execution request'}).innerText()).includes('REQUESTED'));
    await history.getByRole('button',{name:'Request details',exact:true}).click();
    await history.getByRole('heading',{name:'Execution request timeline'}).waitFor();
    await history.getByRole('button',{name:'View execution history',exact:true}).click();
    await history.getByText('No retained attempt records.',{exact:true}).waitFor();
    await page.screenshot({path:`${output}/02-request-history.png`,fullPage:true});
    const hash=new URL(page.url()).hash;assert.match(hash,/page=history/);
    await logout();await browser.close();browser=undefined;await f.restart();await launch();
    await signIn(f.actors[0],hash);
    history=page.getByRole('region',{name:'Consolidated migration history'});
    await history.getByLabel('Search migration history').fill(planId);
    await history.getByText('Execution request',{exact:true}).first().waitFor();
    const retained=(await f.api('GET',`/api/execution-jobs/${job.id}`)).json().job;assert.equal(retained.state,'WAITING_VALIDATION');
    assert.equal((await f.db.sql`SELECT count(*)::int AS n FROM sf_execution_attempts WHERE job_id=${job.id}`)[0].n,0);
    const persisted=await f.api('GET',`${f.base}/plans/${planId}/comparisons/${comparison.id}`);
    assert.equal(persisted.statusCode,200,persisted.body);assert.equal(persisted.json().comparison.digest,comparison.digest);
    await history.getByRole('button',{name:'Open release',exact:true}).first().click();
    await page.getByText('AUTHORED SQL RELEASE',{exact:true}).waitFor();
    await page.getByText(/has not been published to the bound repository/).waitFor();
    await page.screenshot({path:`${output}/03-authored-origin-after-restart.png`,fullPage:true});
    await f.membership.revoke(f.project.id,f.actors[0].id);
    assert.equal((await f.api('GET',`${f.base}/migration-history`)).statusCode,404);
    assert.equal((await f.api('GET',`${f.base}/sql-drafts/${draftId}`)).statusCode,404);
    assert.deepEqual(errors,[]);
    await writeFile(`${output}/workflow-result.json`,JSON.stringify({status:'PASS',scope:'LOCAL_HTTPS_POSTGRESQL',
      draftSavedReopenedValidated:true,multiFileVersions:release.files.map(file=>file.version),authoredReleaseOrigin:true,
      comparisonId:comparison.id,comparisonDigest:comparison.digest,sourceLinkedComment:true,independentApproval:true,
      requestState:'WAITING_VALIDATION',historyFilteringNavigation:true,projectIsolation:true,restartPersistence:true,
      oracleAcceptance:'NOT_RUN',oracleExecution:false},null,2)+'\n');
  } finally {
    if(page && !page.isClosed()) await page.screenshot({path:`${output}/last-state.png`,fullPage:true}).catch(()=>{});await browser?.close();await f?.close();await cert.close();}
});
